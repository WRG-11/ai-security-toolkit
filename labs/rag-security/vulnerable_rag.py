def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="RAG Security Lab -- a vulnerable RAG system",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Examples:\n"
            "  %(prog)s --setup                                   # Create the database\n"
            "  %(prog)s --attack --provider ollama --model <m>    # Attack demo\n"
            "  %(prog)s --attack --defend --provider openai --model <m>\n"
            "  %(prog)s -q 'question' --provider gemini --model <m>\n"
            "\nKeys are read from the environment (OPENAI_API_KEY, ANTHROPIC_API_KEY,\n"
            "GEMINI_API_KEY, or --api-key-env). There is no default model.\n"
        ),
    )
    parser.add_argument("--setup", action="store_true", help="Create the database")
    parser.add_argument("--interactive", "-i", action="store_true", help="Interactive mode")
    parser.add_argument("--query", "-q", help="Ask a single question")
    parser.add_argument("--attack", "-a", action="store_true", help="Attack scenarios")
    parser.add_argument("--defend", "-d", action="store_true", help="Enable the defense layers")
    parser.add_argument("--verbose", "-v", action="store_true", help="Verbose output")
    parser.add_argument("--json", "-j", action="store_true", help="JSON output")
    parser.add_argument("--provider", choices=PROVIDERS, help="Which API the answering model speaks")
    parser.add_argument("--model", "-m", help="Answering model (no default)")
    parser.add_argument("--base-url", help="Endpoint base URL (openai-compatible)")
    parser.add_argument("--api-key-env", metavar="VAR", help="Environment variable holding the API key")
    parser.add_argument("--max-tokens", type=int, default=256,
                        help="Cap each answer (default: 256, the lab's original bound)")
    parser.add_argument("--temperature", type=float, default=0.1,
                        help="Sampling temperature (default: 0.1, as the published numbers were measured)")
    return parser


def target_from_args(args: argparse.Namespace, env=None) -> tuple[Target | None, list[str]]:
    """(target or None, deprecation warnings). None when no model was asked for."""
    env = os.environ if env is None else env
    warnings: list[str] = []
    provider = args.provider
    if provider is None and args.model:
        provider = "ollama"
        warnings.append("--model without --provider is deprecated; use --provider ollama --model "
                        f"{args.model}")
    if provider is None:
        return None, warnings
    return build_target(provider, args.model or "", base_url=args.base_url, api_key_env=args.api_key_env,
                        env=env, max_tokens=args.max_tokens, temperature=args.temperature), warnings


def main():
    parser = build_parser()
    args = parser.parse_args()
    if not (args.setup or args.attack or args.query or args.interactive):
        parser.print_help()
        return
    try:
        target, warnings = target_from_args(args)
    except ValueError as e:
        print(f"[ERROR] {e}", file=sys.stderr)
        sys.exit(2)
    for w in warnings:
        print(f"[DEPRECATED] {w}", file=sys.stderr)
    if target is None and not args.setup:
        print("[ERROR] no model to answer with: pass --provider and --model", file=sys.stderr)
        sys.exit(2)
    rag = VulnerableRAG(defend=args.defend, target=target)

    if args.setup:
        rag.setup_db()
        return

    if args.attack:
        mode = "DEFENDED" if args.defend else "UNDEFENDED"
        print(f"\n  RAG Security Lab -- {mode} MODE")
        run_attacks(rag, verbose=args.verbose)
        return

    if args.query:
        result = rag.query(args.query, verbose=args.verbose)
        if args.json:
            print(json.dumps(result, ensure_ascii=False, indent=2))
        else:
            print(f"\nQuestion: {args.query}")
            safe = result["answer"].encode("ascii", "replace").decode("ascii")
            print(f"Answer: {safe}")
            print(f"Documents: {[d['id'] for d in result['retrieved_docs']]}")
        return

    if args.interactive:
        mode = "DEFENDED" if args.defend else "UNDEFENDED"
        print(f"\nRAG Security Lab -- {mode} interactive mode")
        print(f"Model: {getattr(rag.target, 'model', '?')}")
        print("Type 'exit' to quit\n")
        while True:
            try:
                q = input(">>> ").strip()
                if q.lower() in ("exit", "quit", "q"):
                    break
                if not q:
                    continue
                result = rag.query(q, verbose=True)
                safe = result["answer"].encode("ascii", "replace").decode("ascii")
                print(f"\n{safe}\n")
                if args.verbose:
                    print(f"  Docs: {[d['id'] for d in result['retrieved_docs']]}\n")
            except (KeyboardInterrupt, EOFError):
                break


if __name__ == "__main__":
    main()
