def run_attacks(rag: VulnerableRAG, verbose: bool = True):
    """Run the attack scenarios."""
    results = []

    for scenario in ATTACK_SCENARIOS:
        print(f"\n{'=' * 60}")
        print(f"  ATTACK: {scenario['name']}")
        print(f"  OWASP:   {scenario['owasp']}")
        print(f"  ATLAS:   {scenario['atlas']}")
        print(f"{'=' * 60}")
        print(f"  {scenario['description']}\n")

        for query in scenario["queries"]:
            print(f"  Q: {query[:70]}...")
            try:
                result = rag.query(query, verbose=True)
                answer = result["answer"]
                # Check for sensitive-data leakage
                leaked = find_leaks(answer)

                status = "LEAKED" if leaked else "BLOCKED"
                color = "\033[91m" if leaked else "\033[92m"
                reset = "\033[0m"

                safe_answer = answer[:120].replace("\n", " ").encode("ascii", "replace").decode("ascii")
                print(f"  A: {safe_answer}...")
                print(f"  {color}[{status}]{reset}", end="")
                if leaked:
                    print(f" Leaked: {', '.join(leaked)}")
                else:
                    print()

                results.append({
                    "scenario": scenario["name"],
                    "query": query,
                    "leaked": leaked,
                    "status": status,
                    "docs": [d["id"] for d in result["retrieved_docs"]],
                })
            except Exception as e:
                err = str(e).encode("ascii", "replace").decode("ascii")
                print(f"  [ERROR] {err[:80]}")

            print()

    # Summary
    total = len(results)
    leaked_count = sum(1 for r in results if r["leaked"])
    print(f"\n{'=' * 60}")
    print("  ATTACK SUMMARY")
    print(f"{'=' * 60}")
    print(f"  Total queries: {total}")
    print(f"  Leaked:        {leaked_count} ({leaked_count/max(total,1)*100:.0f}%)")
    print(f"  Blocked:       {total - leaked_count}")
    print(f"{'=' * 60}")

    return results


